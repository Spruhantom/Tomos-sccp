#!/usr/bin/env python3
"""Validate and render safe, TomOS-owned chan-sccp device/line include files.

This tool deliberately does not edit /etc/asterisk/sccp.conf or deploy TFTP files.
"""
import argparse
import json
import os
import pathlib
import re
import sys
import tempfile
from collections import OrderedDict

MAC_RE = re.compile(r"^[0-9A-Fa-f]{12}$")
EXT_RE = re.compile(r"^[0-9]{1,20}$")
MODEL_RE = re.compile(r"^[0-9]{3,4}$")
CONTEXT_RE = re.compile(r"^[A-Za-z0-9_.-]{1,80}$")


class ProvisioningError(ValueError):
    """Raised for invalid provisioning input."""


def text_field(value, field, *, required=True, limit=80):
    if value is None and not required:
        return ""
    if not isinstance(value, str) or (required and not value.strip()):
        raise ProvisioningError(f"{field} must be a non-empty string")
    if len(value) > limit or any(ord(ch) < 32 or ord(ch) == 127 for ch in value):
        raise ProvisioningError(f"{field} contains control characters or exceeds {limit} characters")
    if any(ch in value for ch in ";[]=#"):
        raise ProvisioningError(f"{field} contains a character unsafe for an Asterisk config value")
    return value.strip()


def load_config(path):
    try:
        data = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ProvisioningError(f"cannot read JSON input: {exc}") from exc
    if not isinstance(data, dict) or set(data) - {"server", "devices"}:
        raise ProvisioningError("top-level JSON must contain only 'server' and 'devices'")
    server = data.get("server", {})
    if not isinstance(server, dict) or set(server) - {"context"}:
        raise ProvisioningError("'server' must be an object containing only 'context'")
    context = text_field(server.get("context", "from-internal-xfer"), "server.context")
    if not CONTEXT_RE.fullmatch(context):
        raise ProvisioningError("server.context may contain only letters, digits, dot, underscore and hyphen")
    devices = data.get("devices")
    if not isinstance(devices, list) or not devices:
        raise ProvisioningError("'devices' must be a non-empty array")
    normalized = []
    seen_macs = set()
    lines = OrderedDict()
    for index, item in enumerate(devices):
        prefix = f"devices[{index}]"
        if not isinstance(item, dict):
            raise ProvisioningError(f"{prefix} must be an object")
        allowed = {"mac", "model", "description", "extension", "label", "cid_name", "cid_num"}
        if set(item) - allowed:
            raise ProvisioningError(f"{prefix} has unknown fields: {', '.join(sorted(set(item) - allowed))}")
        mac = text_field(item.get("mac"), f"{prefix}.mac", limit=12).upper()
        if not MAC_RE.fullmatch(mac):
            raise ProvisioningError(f"{prefix}.mac must be exactly 12 hexadecimal characters (no separators)")
        if mac in seen_macs:
            raise ProvisioningError(f"duplicate device MAC: {mac}")
        seen_macs.add(mac)
        model = text_field(item.get("model"), f"{prefix}.model", limit=4)
        if not MODEL_RE.fullmatch(model):
            raise ProvisioningError(f"{prefix}.model must be a 3- or 4-digit Cisco model number")
        extension = text_field(item.get("extension"), f"{prefix}.extension", limit=20)
        if not EXT_RE.fullmatch(extension):
            raise ProvisioningError(f"{prefix}.extension must contain 1–20 digits")
        description = text_field(item.get("description", f"Cisco {model}"), f"{prefix}.description")
        label = text_field(item.get("label", extension), f"{prefix}.label")
        cid_name = text_field(item.get("cid_name", label), f"{prefix}.cid_name")
        cid_num = text_field(item.get("cid_num", extension), f"{prefix}.cid_num", limit=40)
        line = {"extension": extension, "label": label, "description": label,
                "context": context, "cid_name": cid_name, "cid_num": cid_num}
        previous = lines.get(extension)
        if previous is not None and previous != line:
            raise ProvisioningError(
                f"extension {extension} is shared by multiple devices but has conflicting line settings")
        lines.setdefault(extension, line)
        normalized.append({"mac": mac, "model": model, "description": description,
                           "extension": extension})
    return normalized, list(lines.values())


def render_files(devices, lines):
    hardware = [
        "; Generated by tomos-sccp-provision.py. Review before including in sccp.conf.",
        "; Device sections only; no global network allow-list is changed.",
        ""
    ]
    for device in devices:
        hardware.extend([
            f"[SEP{device['mac']}]",
            "type = device",
            f"devicetype = {device['model']}",
            f"description = {device['description']}",
            f"button = line, {device['extension']}",
            ""
        ])
    extensions = [
        "; Generated by tomos-sccp-provision.py. Review before including in sccp.conf.",
        "; Line contexts must exist in the Asterisk dialplan.",
        ""
    ]
    for line in lines:
        extensions.extend([
            f"[{line['extension']}]",
            "type = line",
            "id = 1",
            f"label = {line['label']}",
            f"description = {line['description']}",
            f"context = {line['context']}",
            f"cid_name = {line['cid_name']}",
            f"cid_num = {line['cid_num']}",
            ""
        ])
    return {"sccp_hardware.conf": "\n".join(hardware),
            "sccp_extensions.conf": "\n".join(extensions)}


def atomic_write(path, content, force=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not force:
        raise ProvisioningError(f"refusing to overwrite {path}; use --force after backing it up")
    if path.exists():
        backup = path.with_name(path.name + ".tomos-backup")
        if backup.exists():
            raise ProvisioningError(f"backup already exists: {backup}; move it before using --force")
        os.replace(path, backup)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(content)
        os.chmod(temporary, 0o640)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    for command in ("validate", "render"):
        child = sub.add_parser(command)
        child.add_argument("--input", required=True, help="JSON device inventory")
        if command == "render":
            child.add_argument("--output-dir", required=True, help="staging directory for generated include files")
            child.add_argument("--force", action="store_true", help="replace existing outputs after preserving .tomos-backup copies")
    args = parser.parse_args()
    try:
        devices, lines = load_config(args.input)
        if args.command == "validate":
            print(f"Valid: {len(devices)} device(s), {len(lines)} unique line(s)")
            return 0
        outputs = render_files(devices, lines)
        destination = pathlib.Path(args.output_dir)
        # Preflight the complete output set so a collision cannot leave a partial render.
        for name in outputs:
            target = destination / name
            backup = target.with_name(target.name + ".tomos-backup")
            if target.exists() and not args.force:
                raise ProvisioningError(f"refusing to overwrite {target}; use --force after backing it up")
            if target.exists() and args.force and backup.exists():
                raise ProvisioningError(f"backup already exists: {backup}; move it before using --force")
        for name, content in outputs.items():
            atomic_write(destination / name, content, args.force)
        print(f"Rendered {len(devices)} device(s) and {len(lines)} unique line(s) into {destination}")
        print("These are staging files only; no live Asterisk or TFTP configuration was changed.")
        return 0
    except ProvisioningError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
